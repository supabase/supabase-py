-- The tables of the typed query builder tests, next to the ones the string
-- builder tests read. The rows the tests write get ids from 100 on, so they
-- never collide with the rows seeded here.

create table public.books (
    id int8 generated by default as identity primary key,
    title text not null,
    isbn text unique,
    pages int4 not null default 0,
    published_on date,
    tags text[] not null default '{}',
    metadata jsonb
);

insert into public.books (id, title, isbn, pages, published_on, tags, metadata) values
    (1, 'Dune', '9780441013593', 412, '1965-08-01', '{"science fiction"}', '{"awards": ["Hugo", "Nebula"]}'),
    (2, 'Neuromancer', '9780441569595', 271, '1984-07-01', '{"science fiction", "cyberpunk"}', '{"awards": ["Hugo", "Nebula", "Philip K. Dick"]}'),
    (3, 'Untitled', null, 0, null, '{}', null);

select setval(pg_get_serial_sequence('public.books', 'id'), 99);

create function public.title_upper(public.books)
    returns text
    language sql
    immutable
as $function$
    select upper($1.title);
$function$;

create view public.book_titles as
    select id, title from public.books;

create extension if not exists postgis with schema extensions;

create table public.places (
    id int8 primary key,
    name text not null,
    location extensions.geometry(Point, 4326)
);

insert into public.places (id, name, location) values
    (1, 'Null Island', extensions.st_setsrid(extensions.st_makepoint(0, 0), 4326)),
    (2, 'Nowhere', null);

grant select, insert, update, delete on public.books to anon;
grant select on public.book_titles to anon;
grant select on public.places to anon;
grant execute on function public.title_upper(public.books) to anon;

-- A dry run asks PostgREST to roll back with Prefer: tx=rollback, which it
-- honors only with this setting.
alter role authenticator set pgrst.db_tx_end = 'commit-allow-override';

-- The stack loads safeupdate for the API role, which rejects an update or a
-- delete without a WHERE clause before PostgREST sees the rows it affects.
-- The tests of all() send exactly that, on purpose and in a dry run.
alter role authenticator set safeupdate.enabled = false;
